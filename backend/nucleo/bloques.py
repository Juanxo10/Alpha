def acciones(c, usuario, ruta, d):
    if ruta == "/api/bloque/simular":
        return simular(c, d)
    if ruta == "/api/bloque/vender":
        return vender(c, usuario, d)
    if ruta == "/api/bloque/pago/simular":
        det, rep = repartir_pago(c, d.get("bloque_id"), d.get("valor"))
        return {"reparto": rep}
    if ruta == "/api/bloque/pago":
        return pagar(c, usuario, d)
    if ruta == "/api/bloque/descuentos":
        reglas = [[int(a), float(b)] for a, b in (d.get("reglas") or []) if int(a) >= 2 and 0 <= float(b) <= 50]
        base.set_config(c, "bloque_descuentos", json.dumps(sorted(reglas)))
        bitacora(c, usuario, "BLOQUE_DESCUENTOS", None, {"reglas": sorted(reglas)})
        return {"ok": True}
    return None


