"""Venta en bloque: un comprador adquiere varios lotes en una sola operación.

Estructura contable
  · Se crea un NEGOCIO EN BLOQUE (NEG-0001) y, dentro de él, una venta por cada lote. Cada lote conserva su venta
    porque se escritura, se paga a paz y salvo, se desiste o se cede por separado.
  · El precio del bloque (lista − descuento por volumen) se reparte entre los lotes según su precio de lista.
  · UN SOLO PLAN DE PAGOS para el comprador, que cuadra exacto con la suma de los planes de los lotes:
      PROGRESIVO (recomendado): la inicial y las cuotas pagan los lotes en orden, uno tras otro; el primero queda
                  pagado antes y se puede escriturar mientras se sigue pagando el resto.
      PAREJO:     todos los lotes avanzan al mismo ritmo (la inicial y cada cuota se reparten entre todos).
  · Un pago del bloque se reparte solo entre los lotes por la fecha de vencimiento de sus cuotas: cada lote genera su
    recibo de caja y el conjunto queda en un RECIBO CONSOLIDADO (RCB-0001). En la conciliación bancaria, la
    transferencia única del comprador se cruza contra el recibo consolidado.
  · Descuento por volumen: tabla configurable (cantidad mínima de lotes → % máximo que un operador puede dar sin
    aprobación). Por encima, la venta queda pendiente de aprobación de un dueño.
"""
import datetime as dt
import json

from . import base, cartera, finanzas, seguridad, ventas_lite
from .base import ErrorNegocio, ahora, bitacora, config, hoy, num, sumar_meses

ESQUEMA = """
CREATE TABLE IF NOT EXISTS bloques (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT UNIQUE, cliente_id INTEGER REFERENCES clientes(id), fecha_venta TEXT,
  modo TEXT NOT NULL, n_lotes INTEGER, valor_lista DOUBLE PRECISION, descuento_pct DOUBLE PRECISION, valor_total DOUBLE PRECISION, cuota_inicial DOUBLE PRECISION,
  n_cuotas INTEGER, fecha_primera_cuota TEXT, comisionista_id INTEGER, comision_pct DOUBLE PRECISION, vendedor TEXT, observacion TEXT,
  usuario TEXT, creado TEXT);
CREATE TABLE IF NOT EXISTS bloque_lotes (
  bloque_id INTEGER NOT NULL REFERENCES bloques(id), venta_id INTEGER NOT NULL REFERENCES ventas(id), id_lote TEXT, orden INTEGER,
  precio_lista DOUBLE PRECISION, valor DOUBLE PRECISION, inicial DOUBLE PRECISION, n_cuotas INTEGER, fecha_primera TEXT, PRIMARY KEY (bloque_id, venta_id));
CREATE INDEX IF NOT EXISTS ix_bloque_lotes_venta ON bloque_lotes(venta_id);
CREATE TABLE IF NOT EXISTS bloque_pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT UNIQUE, bloque_id INTEGER NOT NULL REFERENCES bloques(id), fecha TEXT,
  valor DOUBLE PRECISION, medio TEXT, referencia TEXT, observacion TEXT, pagos TEXT, conciliado INTEGER DEFAULT 0, usuario TEXT, creado TEXT);
"""
DESCUENTOS_DEFECTO = [[3, 5], [5, 8], [10, 10]]          # desde N lotes → hasta X % sin aprobación
MODOS = {"PROGRESIVO": "Progresivo: lote por lote (escritura escalonada)", "PAREJO": "Parejo: todos los lotes al mismo ritmo"}


def _pesos(v):
    return "$" + format(int(round(num(v, 0))), ",d").replace(",", ".")


# ---------------------------------------------------------------- arranque y reglas de seguridad
def iniciar(c):
    base.crear_tablas(c, ESQUEMA)
    seguridad.LIBRE_OPERADOR.update({"/api/bloque/simular", "/api/bloque/pago", "/api/bloque/pago/simular"})
    seguridad.SOLO_DUENO.add("/api/bloque/descuentos")
    if not getattr(seguridad.evaluar, "_nf_bloques", False):
        evaluar_base = seguridad.evaluar

        def evaluar(c2, sesion, ruta, d):
            if ruta == "/api/bloque/vender" and sesion["rol"] == "OPERADOR":
                s = simular(c2, d)
                return "aprobacion" if s["requiere_aprobacion"] else "ok"
            return evaluar_base(c2, sesion, ruta, d)
        evaluar._nf_bloques = True
        seguridad.evaluar = evaluar
        resumen_base = seguridad.resumen_solicitud

        def resumen(c2, ruta, d):
            if ruta == "/api/bloque/vender":
                s = simular(c2, d)
                sin = f"; lotes sin precio de lista (precio puesto por el vendedor): {', '.join(s['sin_lista'])}" if s["sin_lista"] else ""
                return (f"Vender en bloque {len(s['lotes'])} lotes ({', '.join(x['id_lote'] for x in s['lotes'])}) a "
                        f"{(d.get('cliente') or {}).get('nombre', '')} por {_pesos(s['valor_total'])}: descuento "
                        f"{s['descuento_pct']:.1f} % sobre {_pesos(s['valor_lista'])} (permitido {s['descuento_permitido']:.1f} %){sin}",
                        s["lotes"][0]["id_lote"] if s["lotes"] else None)
            return resumen_base(c2, ruta, d)
        resumen._nf_bloques = True
        seguridad.resumen_solicitud = resumen
    # conciliación: la transferencia única del comprador se cruza contra el recibo consolidado del bloque
    if not getattr(finanzas.analizar_extracto, "_nf_bloques", False):
        analizar_base, confirmar_base = finanzas.analizar_extracto, finanzas.confirmar_conciliacion

        def analizar(c2, d):
            return _cruzar_bloques(c2, analizar_base(c2, d))

        def confirmar(c2, usuario, d):
            pares, grupos = [], []
            for p in d.get("pares", []):
                if p.get("tabla") == "pagos" and int(p.get("id") or 0) < 0:
                    g = c2.execute("SELECT * FROM bloque_pagos WHERE id=?", (-int(p["id"]),)).fetchone()
                    if g:
                        grupos.append(g["id"])
                        pares += [{"tabla": "pagos", "id": pid} for pid in json.loads(g["pagos"] or "[]")]
                else:
                    pares.append(p)
            r = confirmar_base(c2, usuario, {**d, "pares": pares})
            for gid in grupos:
                c2.execute("UPDATE bloque_pagos SET conciliado=1 WHERE id=?", (gid,))
            return r
        analizar._nf_bloques = confirmar._nf_bloques = True
        finanzas.analizar_extracto, finanzas.confirmar_conciliacion = analizar, confirmar


def descuentos(c):
    try:
        reglas = json.loads(config(c).get("bloque_descuentos") or "null") or DESCUENTOS_DEFECTO
    except ValueError:
        reglas = DESCUENTOS_DEFECTO
    return sorted([[int(a), float(b)] for a, b in reglas])


def descuento_permitido(c, n):
    return max([p for desde, p in descuentos(c) if n >= desde] or [0.0])


# ---------------------------------------------------------------- reparto del bloque entre los lotes
def _repartir(total, pesos_):
    """Reparte un entero total según pesos, con redondeo que conserva la suma exacta."""
    s = sum(pesos_) or 1
    crudo = [total * w / s for w in pesos_]
    out = [int(x) for x in crudo]
    for i in sorted(range(len(crudo)), key=lambda k: crudo[k] - out[k], reverse=True)[:total - sum(out)]:
        out[i] += 1
    return out


def armar(lotes, valor_total, inicial, n, fecha_venta, fecha_primera, modo):
    """lotes: [{id_lote, precio_lista}] en el orden elegido. Devuelve las condiciones de cada venta del bloque."""
    valores = _repartir(int(round(valor_total)), [x["precio_lista"] for x in lotes])
    inicial = min(int(round(inicial)), int(round(valor_total)))
    filas = []
    if modo == "PAREJO":
        inis = _repartir(inicial, valores)
        for x, v, i in zip(lotes, valores, inis):
            filas.append({**x, "valor": v, "inicial": i, "n_cuotas": n if v - i > 0 else 0, "fecha_primera": fecha_primera.isoformat()})
        return filas
    # PROGRESIVO con cuota fija: cada lote recibe un número entero de cuotas iguales (C) y la inicial completa la
    # diferencia de cada lote; los meses se toman de los primeros lotes, que así quedan pagados antes.
    if n > 0 and valor_total - inicial > 0:
        c_fija = round((valor_total - inicial) / n)
        meses = [int(v // c_fija) for v in valores] if c_fija > 0 else []
        exceso = sum(meses) - n
        if c_fija > 0 and exceso >= 0:
            for k in range(len(meses)):
                quita = min(exceso, meses[k])
                meses[k] -= quita
                exceso -= quita
            inis = [v - m * c_fija for v, m in zip(valores, meses)]
            inis[-1] = inicial - sum(inis[:-1])
            if all(0 <= i <= v for i, v in zip(inis, valores)):
                corrido = 0
                for x, v, i, m in zip(lotes, valores, inis, meses):
                    filas.append({**x, "valor": v, "inicial": i, "n_cuotas": m, "fecha_primera": sumar_meses(fecha_primera, corrido).isoformat()})
                    corrido += m
                return filas
    # si la inicial no alcanza para cuadrar cuotas fijas: la inicial cubre los lotes en orden y las cuotas varían poco
    resto_ini = inicial
    for x, v in zip(lotes, valores):
        i = min(v, resto_ini)
        resto_ini -= i
        filas.append({**x, "valor": v, "inicial": i, "resto": v - i})
    financiado = sum(f["resto"] for f in filas)
    if n <= 0 or financiado <= 0:
        for f in filas:
            f.update(n_cuotas=0, fecha_primera=fecha_primera.isoformat())
            f.pop("resto")
        return filas
    cuota = financiado / n
    ideal = [f["resto"] / cuota for f in filas]
    meses = [int(m) for m in ideal]
    for k in sorted(range(len(filas)), key=lambda j: ideal[j] - meses[j], reverse=True)[:n - sum(meses)]:
        meses[k] += 1
    for k, f in enumerate(filas):            # todo lote con saldo necesita al menos una cuota
        if f["resto"] > 0 and meses[k] == 0:
            donante = max(range(len(filas)), key=lambda j: meses[j])
            if meses[donante] > 1:
                meses[donante] -= 1
                meses[k] = 1
    corrido = 0
    for k, f in enumerate(filas):
        f["n_cuotas"] = meses[k] if f["resto"] > 0 else 0
        f["fecha_primera"] = sumar_meses(fecha_primera, corrido).isoformat()
        corrido += f["n_cuotas"]
        f.pop("resto")
    return filas


def _plan_lote(f, fecha_venta):
    v = {"etapa": "VENDIDO", "valor_venta": f["valor"], "fecha_venta": fecha_venta.isoformat(), "cuota_inicial": f["inicial"],
         "n_cuotas": f["n_cuotas"], "fecha_primera_cuota": f["fecha_primera"]}
    return cartera.plan_de_pagos(v)


def consolidar(planes):
    """Plan único del comprador: suma por fecha de los planes de los lotes."""
    por_fecha = {}
    for id_lote, plan in planes:
        for it in plan:
            x = por_fecha.setdefault(it["fecha"], {"fecha": it["fecha"], "valor": 0, "pagado": 0, "pendiente": 0, "lotes": []})
            x["valor"] += it["valor"]
            x["pagado"] += it.get("pagado", 0)
            x["pendiente"] += it.get("pendiente", it["valor"])
            x["lotes"].append(id_lote)
    return [por_fecha[k] for k in sorted(por_fecha)]


def simular(c, d):
    ids = [str(x).strip() for x in (d.get("lotes") or []) if str(x).strip()]
    if len(ids) < 2:
        raise ErrorNegocio("Seleccione al menos dos lotes para una venta en bloque.")
    if len(set(ids)) != len(ids):
        raise ErrorNegocio("Hay lotes repetidos en la selección.")
    precios = {str(k): round(num(v, 0)) for k, v in (d.get("precios") or {}).items() if num(v, 0) > 0}
    lotes, problemas = [], []
    marcas = ",".join("?" * len(ids))
    existentes = {r["id_lote"]: r for r in c.execute(f"SELECT * FROM lotes WHERE id_lote IN ({marcas})", ids)}
    ocupados = {r[0] for r in c.execute(f"SELECT id_lote FROM ventas WHERE estado='ACTIVA' AND id_lote IN ({marcas})", ids)}
    for i in ids:
        l = existentes.get(i)
        if not l:
            problemas.append(f"{i}: no existe")
            continue
        if i in ocupados:
            problemas.append(f"{i}: ya está separado o vendido")
        elif l["bloqueado"]:
            problemas.append(f"{i}: está bloqueado")
        elif not l["precio_lista"] and not precios.get(i):
            problemas.append(f"{i}: no tiene precio de lista; escriba su precio en el formulario")
        lista_real = l["precio_lista"] or 0
        precio = precios.get(i) or lista_real      # el precio escrito manda; la lista real sirve para medir el descuento
        lotes.append({"id_lote": i, "precio_lista": precio, "lista_real": lista_real, "area_m2": l["area_m2"],
                      "sin_lista": not lista_real, "bajo_lista": bool(lista_real and precio < lista_real)})
    if problemas:
        raise ErrorNegocio("No se pueden vender en bloque: " + "; ".join(problemas) + ".")
    lista = sum(x["precio_lista"] for x in lotes)
    lista_ref = sum(x["lista_real"] or x["precio_lista"] for x in lotes)
    if d.get("valor_total") not in (None, "", 0, "0"):
        total = round(num(d["valor_total"]))
    else:
        total = round(lista * (1 - num(d.get("descuento_pct"), 0) / 100))
    if total <= 0:
        raise ErrorNegocio("El valor del bloque debe ser mayor que cero.")
    desc = 100 * (lista_ref - total) / lista_ref if lista_ref else 0
    permitido = descuento_permitido(c, len(lotes))
    inicial, n = round(num(d.get("cuota_inicial"), 0)), int(num(d.get("n_cuotas"), 0))
    if inicial > total:
        raise ErrorNegocio("La cuota inicial no puede superar el valor del bloque.")
    if not 0 <= n <= 360:
        raise ErrorNegocio("Número de cuotas fuera de rango (0 a 360).")
    fv = dt.date.fromisoformat((d.get("fecha_venta") or hoy().isoformat())[:10])
    fp = dt.date.fromisoformat((d.get("fecha_primera_cuota") or sumar_meses(fv, 1).isoformat())[:10])
    modo = d.get("modo") if d.get("modo") in MODOS else "PROGRESIVO"
    filas = armar(lotes, total, inicial, n, fv, fp, modo)
    if n > 0 and any(f["valor"] - f["inicial"] > 0.5 and not f["n_cuotas"] for f in filas):
        raise ErrorNegocio(f"Con {n} cuota(s) no alcanza para pagar los lotes uno por uno: aumente el número de cuotas, "
                           "suba la cuota inicial o use el reparto parejo.")
    planes = []
    for f in filas:
        plan = _plan_lote(f, fv)
        cuotas = [it for it in plan if it["n"] >= 1]
        f["cuota"] = cuotas[0]["valor"] if cuotas else 0
        f["desde"] = cuotas[0]["fecha"] if cuotas else None
        f["hasta"] = cuotas[-1]["fecha"] if cuotas else fv.isoformat()
        planes.append((f["id_lote"], plan))
    plan = consolidar(planes)
    cuotas_mes = [x["valor"] for x in plan if x["fecha"] != fv.isoformat() or not inicial]
    return {"lotes": filas, "plan": plan, "valor_lista": lista_ref, "valor_total": total, "descuento_pct": round(desc, 3),
            "descuento_permitido": permitido, "modo": modo,
            # sin precio de lista el precio lo pone quien vende: si es un operador, lo aprueba un dueño (igual que una venta suelta)
            "sin_lista": [x["id_lote"] for x in lotes if x.get("sin_lista")],
            "requiere_aprobacion": desc > permitido + 1e-9 or any(x.get("sin_lista") or x.get("bajo_lista") for x in lotes),
            "cuota_inicial": inicial, "n_cuotas": n, "fecha_venta": fv.isoformat(), "fecha_primera_cuota": fp.isoformat(),
            "cuota_min": min(cuotas_mes) if cuotas_mes else 0, "cuota_max": max(cuotas_mes) if cuotas_mes else 0,
            "area_total": sum(x["area_m2"] or 0 for x in lotes), "descuentos": descuentos(c)}


def vender(c, usuario, d):
    s = simular(c, d)
    cliente = dict(d.get("cliente") or {})
    if not (cliente.get("nombre") or "").strip():
        raise ErrorNegocio("El nombre del comprador es obligatorio.")
    n_bl = int(config(c).get("consecutivo_bloque") or 1)
    base.set_config(c, "consecutivo_bloque", n_bl + 1)
    numero = f"NEG-{n_bl:04d}"
    obs = (d.get("observacion") or "").strip()
    vids, cid = [], None
    for k, f in enumerate(s["lotes"]):
        datos = {"id_lote": f["id_lote"], "cliente": cliente, "valor_venta": f["valor"], "cuota_inicial": f["inicial"],
                 "n_cuotas": f["n_cuotas"], "fecha_venta": s["fecha_venta"], "fecha_primera_cuota": f["fecha_primera"],
                 "vendedor": d.get("vendedor") or "", "observacion": f"Negocio en bloque {numero} ({len(s['lotes'])} lotes)" + (f". {obs}" if obs else ""),
                 "comisionista_id": d.get("comisionista_id"), "comision_pct": d.get("comision_pct"), "comision_regla": d.get("comision_regla"),
                 "prospecto_id": d.get("prospecto_id") if k == 0 else None}
        cartera.acciones(c, usuario, "/api/venta/vender", datos)
        v = c.execute("SELECT id, cliente_id FROM ventas WHERE id_lote=? AND estado='ACTIVA'", (f["id_lote"],)).fetchone()
        vids.append(v["id"])
        if cid is None:
            cid = v["cliente_id"]
            cliente["id"] = cid           # los demás lotes usan el mismo comprador
    bid = c.execute("INSERT INTO bloques (numero, cliente_id, fecha_venta, modo, n_lotes, valor_lista, descuento_pct, valor_total, cuota_inicial, "
                    "n_cuotas, fecha_primera_cuota, comisionista_id, comision_pct, vendedor, observacion, usuario, creado) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (numero, cid, s["fecha_venta"], s["modo"], len(vids), s["valor_lista"], s["descuento_pct"], s["valor_total"],
                     s["cuota_inicial"], s["n_cuotas"], s["fecha_primera_cuota"], int(d["comisionista_id"]) if d.get("comisionista_id") else None,
                     num(d.get("comision_pct"), 0) or None, d.get("vendedor") or "", obs, usuario, ahora())).lastrowid
    for k, (f, vid) in enumerate(zip(s["lotes"], vids)):
        c.execute("INSERT INTO bloque_lotes (bloque_id, venta_id, id_lote, orden, precio_lista, valor, inicial, n_cuotas, fecha_primera) "
                  "VALUES (?,?,?,?,?,?,?,?,?)", (bid, vid, f["id_lote"], k + 1, f["precio_lista"], f["valor"], f["inicial"], f["n_cuotas"],
                                                 f["fecha_primera"]))
    bitacora(c, usuario, "BLOQUE_VENTA", s["lotes"][0]["id_lote"], {
        "negocio": numero, "lotes": [f["id_lote"] for f in s["lotes"]], "valor_lista": s["valor_lista"], "valor_total": s["valor_total"],
        "descuento_pct": round(s["descuento_pct"], 2), "modo": s["modo"], "cuota_inicial": s["cuota_inicial"], "n_cuotas": s["n_cuotas"]})
    return {"ok": True, "id": bid, "numero": numero, "ventas": vids}


# ---------------------------------------------------------------- estado y pagos del bloque
def _cargar(c, bid):
    """El negocio, sus lotes y el estado de cada venta (pocas consultas aunque sean muchos lotes)."""
    b = c.execute("SELECT b.*, cl.nombre cliente, cl.documento, cl.tipo_doc, cl.telefono, cl.email, cl.direccion FROM bloques b "
                  "LEFT JOIN clientes cl ON cl.id=b.cliente_id WHERE b.id=?", (int(bid or 0),)).fetchone()
    if not b:
        raise ErrorNegocio("Negocio en bloque no encontrado.")
    bls = c.execute("SELECT * FROM bloque_lotes WHERE bloque_id=? ORDER BY orden", (b["id"],)).fetchall()
    return b, bls, ventas_lite.cargar(c, [bl["venta_id"] for bl in bls])


def detalle(c, bid, pre=None, con_pagos=True):
    b, bls, vs = pre or _cargar(c, bid)
    lotes, planes = [], []
    for bl in bls:
        v = vs.get(bl["venta_id"])
        if not v:
            continue
        lotes.append({"id_lote": bl["id_lote"], "venta_id": v["id"], "orden": bl["orden"], "estado": v["estado"], "etapa": v["etapa"],
                      "valor": v["valor_venta"], "pagado": v["pagado"], "saldo": v["saldo"] if v["estado"] == "ACTIVA" else 0,
                      "vencido": v.get("vencido", 0) if v["estado"] == "ACTIVA" else 0, "dias_mora": v.get("dias_mora", 0),
                      "cartera": v.get("cartera"), "area_m2": v["lote"].get("area_m2"), "n_cuotas": bl["n_cuotas"], "pct_pagado": v.get("pct_pagado", 0)})
        if v["estado"] == "ACTIVA":
            planes.append((bl["id_lote"], v["plan"]))
    plan = consolidar(planes)
    pagos = [dict(r) | {"pagos": json.loads(r["pagos"] or "[]")} for r in
             c.execute("SELECT * FROM bloque_pagos WHERE bloque_id=? ORDER BY id DESC", (b["id"],))] if con_pagos else []
    activos = [x for x in lotes if x["estado"] == "ACTIVA"]
    prox = next((x for x in plan if x["pendiente"] > 0.5 and x["fecha"] >= hoy().isoformat()), None)
    return {**dict(b), "modo_nombre": MODOS.get(b["modo"], b["modo"]), "lotes": lotes, "plan": plan, "pagos_bloque": pagos,
            "resumen": {"valor": sum(x["valor"] for x in activos), "pagado": sum(x["pagado"] for x in activos),
                        "saldo": sum(x["saldo"] for x in activos), "vencido": sum(x["vencido"] for x in activos),
                        "dias_mora": max([x["dias_mora"] or 0 for x in activos] or [0]),
                        "lotes_activos": len(activos), "lotes_pagados": sum(1 for x in activos if x["saldo"] <= 0.5),
                        "escriturados": sum(1 for x in activos if x["etapa"] == "ESCRITURADO"),
                        "proxima": prox}}


def repartir_pago(c, bid, valor):
    """Reparte un pago del bloque entre los lotes por la fecha de vencimiento de sus cuotas (lo más antiguo primero;
    las cuotas de la misma fecha se reparten en proporción a lo pendiente)."""
    pre = _cargar(c, bid)
    det = detalle(c, bid, pre)
    pend = []
    for x in det["lotes"]:
        if x["estado"] != "ACTIVA":
            continue
        for it in pre[2][x["venta_id"]]["plan"]:
            if it.get("pendiente", 0) > 0.5:
                pend.append((it["fecha"], x["orden"], x["venta_id"], x["id_lote"], it["pendiente"]))
    total_pend = sum(p[4] for p in pend)
    valor = round(num(valor, 0))
    if valor <= 0:
        raise ErrorNegocio("El valor del pago debe ser mayor que cero.")
    if valor > total_pend + 0.5:
        raise ErrorNegocio(f"El pago supera el saldo del negocio en bloque ({_pesos(total_pend)}).")
    reparto, resto = {}, valor
    for f in sorted({p[0] for p in pend}):
        grupo = [p for p in pend if p[0] == f]
        suma = sum(p[4] for p in grupo)
        if resto <= 0:
            break
        if resto >= suma:
            for p in grupo:
                reparto[p[2]] = reparto.get(p[2], 0) + p[4]
            resto -= suma
        else:
            partes = _repartir(int(resto), [p[4] for p in grupo])
            for p, a in zip(grupo, partes):
                reparto[p[2]] = reparto.get(p[2], 0) + a
            resto = 0
    lotes = {x["venta_id"]: x["id_lote"] for x in det["lotes"]}
    return det, [{"venta_id": k, "id_lote": lotes[k], "valor": round(v)} for k, v in reparto.items() if round(v) > 0]


def pagar(c, usuario, d):
    det, reparto = repartir_pago(c, d.get("bloque_id"), d.get("valor"))
    fecha = (d.get("fecha") or hoy().isoformat())[:10]
    n = int(config(c).get("consecutivo_recibo_bloque") or 1)
    base.set_config(c, "consecutivo_recibo_bloque", n + 1)
    numero = f"RCB-{n:04d}"
    ids, recibos = [], []
    for r in reparto:
        p = cartera.registrar_pago(c, usuario, r["venta_id"], {
            "valor": r["valor"], "fecha": fecha, "concepto": d.get("concepto") or "Cuota", "medio": d.get("medio") or "Efectivo",
            "referencia": f"{numero}" + (f" · {d['referencia']}" if d.get("referencia") else ""),
            "observacion": f"Pago del negocio en bloque {det['numero']}" + (f". {d['observacion']}" if d.get("observacion") else "")})
        ids.append(p["pago_id"])
        recibos.append({"recibo": p["recibo"], "id_lote": r["id_lote"], "valor": r["valor"]})
    gid = c.execute("INSERT INTO bloque_pagos (numero, bloque_id, fecha, valor, medio, referencia, observacion, pagos, usuario, creado) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?)", (numero, det["id"], fecha, round(num(d["valor"])), d.get("medio") or "Efectivo",
                                                    d.get("referencia") or "", d.get("observacion") or "", json.dumps(ids), usuario, ahora())).lastrowid
    bitacora(c, usuario, "BLOQUE_PAGO", reparto[0]["id_lote"], {"negocio": det["numero"], "recibo_consolidado": numero,
                                                                "valor": round(num(d["valor"])), "recibos": recibos})
    return {"ok": True, "id": gid, "numero": numero, "recibos": recibos}


def recibo_bloque(c, gid):
    g = c.execute("SELECT * FROM bloque_pagos WHERE id=?", (int(gid or 0),)).fetchone()
    if not g:
        raise ErrorNegocio("Recibo consolidado no encontrado.")
    ids = json.loads(g["pagos"] or "[]")
    pagos = [dict(r) for r in c.execute("SELECT * FROM pagos WHERE id IN (%s) ORDER BY recibo" % ",".join("?" * len(ids)), ids)] if ids else []
    return {**dict(g), "detalle_pagos": pagos, "negocio": detalle(c, g["bloque_id"])}


def _cruzar_bloques(c, r):
    """Conciliación: un movimiento del banco que no cuadró con un recibo individual se compara con los recibos
    consolidados de los bloques (la suma de sus recibos)."""
    try:
        grupos = [dict(g) for g in c.execute("SELECT g.*, cl.nombre cliente, b.numero negocio FROM bloque_pagos g JOIN bloques b ON b.id=g.bloque_id "
                                             "LEFT JOIN clientes cl ON cl.id=b.cliente_id WHERE COALESCE(g.conciliado,0)=0 AND g.medio<>'Efectivo'")]
    except Exception:  # noqa: BLE001
        return r
    usados = set()
    for m in list(r.get("sin_registro", [])):
        if m["valor"] <= 0:
            continue
        for g in grupos:
            if g["id"] in usados or abs(g["valor"] - m["valor"]) > 1:
                continue
            if abs((dt.date.fromisoformat(m["fecha"]) - dt.date.fromisoformat(g["fecha"])).days) > 6:
                continue
            ids = set(json.loads(g["pagos"] or "[]"))
            usados.add(g["id"])
            r["sin_registro"].remove(m)
            r["sin_extracto"] = [x for x in r.get("sin_extracto", []) if not (x.get("tabla") == "pagos" and x.get("id") in ids)]
            r["pares"].append({"movimiento": m, "registro": {"tabla": "pagos", "id": -g["id"], "numero": g["numero"][4:],
                                                            "fecha": g["fecha"], "valor": g["valor"], "medio": g["medio"],
                                                            "tercero": g["cliente"], "id_lote": f"Negocio en bloque {g['negocio']} ({len(ids)} recibos)"}})
            break
    return r


def listar(c):
    out = []
    bloques_ = c.execute("SELECT b.*, cl.nombre cliente, cl.documento, cl.tipo_doc, cl.telefono, cl.email, cl.direccion FROM bloques b "
                         "LEFT JOIN clientes cl ON cl.id=b.cliente_id ORDER BY b.id DESC").fetchall()
    por_bloque = {}
    for bl in c.execute("SELECT * FROM bloque_lotes ORDER BY orden").fetchall():
        por_bloque.setdefault(bl["bloque_id"], []).append(bl)
    vs = ventas_lite.cargar(c, [bl["venta_id"] for x in por_bloque.values() for bl in x])
    for b in bloques_:
        d = detalle(c, b["id"], (b, por_bloque.get(b["id"], []), vs), con_pagos=False)
        out.append({k: d[k] for k in ("id", "numero", "cliente", "documento", "fecha_venta", "modo", "modo_nombre", "n_lotes", "valor_total",
                                      "descuento_pct")} | {"resumen": {k: v for k, v in d["resumen"].items() if k != "proxima"},
                                                           "lotes": [x["id_lote"] for x in d["lotes"]]})
    return {"bloques": out, "descuentos": descuentos(c), "modos": MODOS}


def bloque_de_venta(c, venta_id):
    r = c.execute("SELECT b.id, b.numero, b.n_lotes FROM bloque_lotes bl JOIN bloques b ON b.id=bl.bloque_id WHERE bl.venta_id=?",
                  (int(venta_id or 0),)).fetchone()
