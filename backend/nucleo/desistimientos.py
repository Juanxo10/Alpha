"""Desistimiento con liquidación automática.

Cuando un comprador desiste, lo que se le devuelve es:  lo pagado − cláusula penal − otros descuentos acordados.
  · cláusula penal = % del precio de la venta (por defecto el de la promesa, en Configuración), sin pasar de lo pagado;
  · otros descuentos (gastos, comisión ya pagada…) los digita quien registra, con su concepto, sin pasar de lo que queda;
  · plazo de devolución en días (Configuración); queda la fecha límite y se avisa cuando vence.
El desistimiento cierra el negocio (igual que antes) y deja la liquidación guardada. La devolución se registra después, cuando
se paga: entra como un gasto «Devoluciones a compradores» (comprobante de egreso, sale de la caja y se concilia con el banco).
"""
import datetime as dt

from . import cartera, finanzas, seguridad, ventas_lite
from .base import ErrorNegocio, ahora, bitacora, config, crear_tablas, hoy, num

CATEGORIA = "Devoluciones a compradores"
ESTADOS = {"PENDIENTE": "Por devolver", "DEVUELTA": "Devuelta", "SIN_DEVOLUCION": "Sin devolución"}

ESQUEMA = """
CREATE TABLE IF NOT EXISTS desistimientos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id INTEGER NOT NULL REFERENCES ventas(id), id_lote TEXT,
  fecha TEXT NOT NULL, motivo TEXT, valor_venta DOUBLE PRECISION, pagado DOUBLE PRECISION, penalidad_pct DOUBLE PRECISION,
  retencion DOUBLE PRECISION, otros_descuentos DOUBLE PRECISION, otros_concepto TEXT, devolucion DOUBLE PRECISION,
  plazo_dias INTEGER, fecha_limite TEXT, estado TEXT NOT NULL DEFAULT 'PENDIENTE', gasto_id INTEGER, fecha_devolucion TEXT,
  medio TEXT, referencia TEXT, usuario TEXT, creado TEXT);
CREATE INDEX IF NOT EXISTS ix_desistimientos_venta ON desistimientos(venta_id);
"""
LIBRES = {"/api/desistimiento/simular"}
CON_APROBACION = {"/api/desistimiento/registrar", "/api/desistimiento/devolver"}


def _pesos(v):
    return "$" + format(int(round(num(v, 0))), ",d").replace(",", ".")


def iniciar(c):
    crear_tablas(c, ESQUEMA)
    if CATEGORIA not in finanzas.CATEGORIAS:
        finanzas.CATEGORIAS.insert(finanzas.CATEGORIAS.index("Otros"), CATEGORIA)
    seguridad.LIBRE_OPERADOR.update(LIBRES)
    seguridad.REQUIERE_APROBACION.update(CON_APROBACION)
    if getattr(seguridad.resumen_solicitud, "_nf_desist", False):
        return
    original = seguridad.resumen_solicitud

    def resumen(c2, ruta, d):
        if ruta == "/api/desistimiento/registrar":
            x = calcular(c2, d.get("venta_id"), d.get("penalidad_pct"), d.get("otros_descuentos"), d.get("fecha"))
            return (f"Desistimiento del lote {x['id_lote']} ({x['cliente']}): pagado {_pesos(x['pagado'])}, retención {_pesos(x['retencion'])}"
                    f" ({x['penalidad_pct']:g} % del precio), otros descuentos {_pesos(x['otros_descuentos'])}, a devolver {_pesos(x['devolucion'])}."
                    f" Motivo: {d.get('motivo', '')}", x["id_lote"])
        if ruta == "/api/desistimiento/devolver":
            r = c2.execute("SELECT id_lote, devolucion FROM desistimientos WHERE id=?", (int(d.get("id") or 0),)).fetchone()
            if r:
                return f"Registrar la devolución de {_pesos(r['devolucion'])} al comprador del lote {r['id_lote']} (sale de la caja)", r["id_lote"]
        return original(c2, ruta, d)
    resumen._nf_desist = True
    seguridad.resumen_solicitud = resumen


# ---------------------------------------------------------------- liquidación
def calcular(c, venta_id, penalidad_pct=None, otros=0, fecha_=None):
    v = ventas_lite.cargar(c, [venta_id or 0]).get(int(venta_id or 0))
    if not v:
        raise ErrorNegocio("Negocio no encontrado.")
    cfg = config(c)
    pct = num(penalidad_pct, 0) if penalidad_pct not in (None, "") else num(cfg.get("promesa_penalidad_pct"), 0)
    if not 0 <= pct <= 100:
        raise ErrorNegocio("La cláusula penal debe estar entre 0 y 100 % del precio.")
    if num(otros, 0) < 0:
        raise ErrorNegocio("Los otros descuentos no pueden ser negativos.")
    precio, pagado = round(v["valor_venta"] or 0), round(v["pagado"])
    clausula = round(precio * pct / 100)
    retencion = min(clausula, pagado)
    otros_ef = min(round(num(otros, 0)), pagado - retencion)
    f = (fecha_ or hoy().isoformat())[:10]
    plazo = int(num(cfg.get("desistimiento_plazo_dias"), 30))
    avisos = []
    if clausula > pagado:
        avisos.append(f"La cláusula penal ({_pesos(clausula)}) supera lo pagado: se retiene todo y no hay nada que devolver.")
    if round(num(otros, 0)) > otros_ef:
        avisos.append(f"Los otros descuentos se limitaron a {_pesos(otros_ef)}, que es lo que queda después de la retención.")
    return {"venta_id": v["id"], "id_lote": v["id_lote"], "cliente": v["nombre"], "etapa": v["etapa"], "estado_venta": v["estado"],
            "valor_venta": precio, "pagado": pagado, "penalidad_pct": pct, "clausula_penal": clausula, "retencion": retencion,
            "otros_descuentos": otros_ef, "devolucion": pagado - retencion - otros_ef, "plazo_dias": plazo, "fecha": f,
            "fecha_limite": (dt.date.fromisoformat(f) + dt.timedelta(days=plazo)).isoformat(), "avisos": avisos}


def registrar(c, usuario, d):
    x = calcular(c, d.get("venta_id"), d.get("penalidad_pct"), d.get("otros_descuentos"), d.get("fecha"))
    if x["estado_venta"] != "ACTIVA":
        raise ErrorNegocio("La venta no está activa.")
    if x["otros_descuentos"] > 0 and not (d.get("otros_concepto") or "").strip():
        raise ErrorNegocio("Indique el concepto de los otros descuentos.")
    if dt.date.fromisoformat(x["fecha"]) > hoy():
        raise ErrorNegocio("La fecha del desistimiento no puede ser futura.")
    motivo = (d.get("motivo") or "").strip()
    cartera.acciones(c, usuario, "/api/venta/desistir", {"venta_id": x["venta_id"], "motivo": motivo, "fecha": x["fecha"]})
    did = c.execute(
        "INSERT INTO desistimientos (venta_id, id_lote, fecha, motivo, valor_venta, pagado, penalidad_pct, retencion, otros_descuentos, otros_concepto, "
        "devolucion, plazo_dias, fecha_limite, estado, usuario, creado) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
        (x["venta_id"], x["id_lote"], x["fecha"], motivo, x["valor_venta"], x["pagado"], x["penalidad_pct"], x["retencion"], x["otros_descuentos"],
         (d.get("otros_concepto") or "").strip(), x["devolucion"], x["plazo_dias"], x["fecha_limite"],
         "PENDIENTE" if x["devolucion"] > 0 else "SIN_DEVOLUCION", usuario, ahora())).lastrowid
    bitacora(c, usuario, "DESISTIMIENTO_LIQUIDADO", x["id_lote"], {k: x[k] for k in ("pagado", "penalidad_pct", "retencion", "otros_descuentos", "devolucion", "fecha_limite")})
    return {"ok": True, "id": did, **x}


def devolver(c, usuario, d):
    r = c.execute("SELECT * FROM desistimientos WHERE id=?", (int(d.get("id") or 0),)).fetchone()
    if not r or r["estado"] != "PENDIENTE":
        raise ErrorNegocio("El desistimiento no existe o ya no tiene una devolución pendiente.")
    f = (d.get("fecha") or hoy().isoformat())[:10]
    if dt.date.fromisoformat(f) > hoy() or f < r["fecha"]:
        raise ErrorNegocio("La fecha de la devolución debe estar entre el desistimiento y hoy.")
    cl = c.execute("SELECT cl.nombre, cl.documento FROM ventas v JOIN clientes cl ON cl.id=v.cliente_id WHERE v.id=?", (r["venta_id"],)).fetchone()
    medio = d.get("medio") or "Transferencia"
    g = finanzas.guardar_gasto(c, usuario, {
        "categoria": CATEGORIA, "valor_bruto": r["devolucion"], "retencion": 0, "fecha": f, "medio": medio, "referencia": d.get("referencia") or "",
        "proveedor": cl["nombre"], "documento_proveedor": cl["documento"] or "",
        "descripcion": f"Devolución por desistimiento del lote {r['id_lote']}"})
    c.execute("UPDATE desistimientos SET estado='DEVUELTA', gasto_id=?, fecha_devolucion=?, medio=?, referencia=? WHERE id=?",
              (g["id"], f, medio, d.get("referencia") or "", r["id"]))
    bitacora(c, usuario, "DESISTIMIENTO_DEVUELTO", r["id_lote"], {"devolucion": r["devolucion"], "comprobante": g["comprobante"], "fecha": f})
    return {"ok": True, "comprobante": g["comprobante"]}


# ---------------------------------------------------------------- consultas
def _fila(r):
    x = dict(r)
    x["estado_nombre"] = ESTADOS.get(r["estado"], r["estado"])
    x["vencida"] = r["estado"] == "PENDIENTE" and r["fecha_limite"] < hoy().isoformat()
    x["dias_para_vencer"] = (dt.date.fromisoformat(r["fecha_limite"]) - hoy()).days if r["estado"] == "PENDIENTE" else None
    return x


def listar(c, venta_id=None):
    sql = ("SELECT d.*, cl.nombre cliente, cl.documento, v.etapa FROM desistimientos d JOIN ventas v ON v.id=d.venta_id "
           "JOIN clientes cl ON cl.id=v.cliente_id")
    filas = [_fila(r) for r in (c.execute(sql + " WHERE d.venta_id=? ORDER BY d.id DESC", (int(venta_id),)) if venta_id
                                 else c.execute(sql + " ORDER BY d.id DESC"))]
    pend = [f for f in filas if f["estado"] == "PENDIENTE"]
    return {"desistimientos": filas, "plazo_dias": int(num(config(c).get("desistimiento_plazo_dias"), 30)),
            "kpis": {"por_devolver_n": len(pend), "por_devolver": sum(f["devolucion"] for f in pend), "vencidas": sum(1 for f in pend if f["vencida"]),
                     "devuelto": sum(f["devolucion"] for f in filas if f["estado"] == "DEVUELTA"), "retenido": sum(f["retencion"] + f["otros_descuentos"] for f in filas)}}


def get(c, sesion, ruta, q):
    if ruta == "/api/desistimientos":
        return listar(c, q.get("venta_id"))
    return None


def acciones(c, usuario, ruta, d):
    if ruta == "/api/desistimiento/simular":
        return calcular(c, d.get("venta_id"), d.get("penalidad_pct"), d.get("otros_descuentos"), d.get("fecha"))
    if ruta == "/api/desistimiento/registrar":
        return registrar(c, usuario, d)
    if ruta == "/api/desistimiento/devolver":
        return devolver(c, usuario, d)
    return None
