def sumar_meses(d, n):
    m = d.month - 1 + n
    a, m = d.year + m // 12, m % 12 + 1
    return dt.date(a, m, min(d.day, calendar.monthrange(a, m)[1]))


def num(v, defecto=0.0):
    if v in (None, ""):
        return defecto
    return float(str(v).replace(",", "."))


def memo(clave, f, ttl=60):
    """Guarda en memoria el resultado de una lectura hasta la próxima escritura DEL MISMO CLIENTE (cada consulta a Supabase cuesta ~140 ms)."""
    t = tenant.actual()
    v, e = t.version[0], t.memo.get(clave)
    if e and e[0] == v and time.time() - e[1] < ttl:
        return e[2]
    r = f()
    t.memo[clave] = (v, time.time(), r)
    return r


class Fila(tuple):
    """Fila que se lee como fila: por posición, por nombre, dict(fila) y fila.keys()."""
    def __new__(cls, valores, nombres):
        f = super().__new__(cls, valores)
        f._n = nombres
        return f

    def __getitem__(self, k):
        return super().__getitem__(self._n.index(k) if isinstance(k, str) else k)

    def keys(self):
        return list(self._n)


def _fila(cur):
    nombres = [d.name for d in cur.description] if cur.description else []
    return lambda valores: Fila(valores, nombres)


