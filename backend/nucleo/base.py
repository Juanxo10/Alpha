class Resultado:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid, self.rowcount = cur, lastrowid, cur.rowcount

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)


class ConexionPG:
    """Hace que una conexión de Postgres se use igual que la de SQLite: ? como marcador, lastrowid, INSERT OR IGNORE."""
    def __init__(self, con, pool, t):
        self.con, self.pool, self.t = con, pool, t
        self.en_tx = False      # autocommit: las lecturas no pagan BEGIN/COMMIT (cada viaje a Supabase cuesta ~130 ms)

    @staticmethod
    def _traducir(sql):
        sql = re.sub(r"LIKE", "ILIKE", sql.replace("%", "%%").replace("?", "%s"))     # LIKE de SQLite no distingue mayúsculas
        if re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO", sql, re.I):
            sql = re.sub(r"INSERT\s+OR\s+IGNORE", "INSERT", sql, count=1, flags=re.I) + " ON CONFLICT DO NOTHING"
        return sql

    def execute(self, sql, params=()):
        sql = self._traducir(sql)
        tabla = re.match(r"\s*INSERT\s+INTO\s+(\w+)", sql, re.I)
        con_id = bool(tabla) and tabla.group(1) in _CON_ID
        if con_id:
            sql += " RETURNING id"
        self._abrir(sql)
        cur = self.con.cursor(row_factory=_fila)
        cur.execute(sql, tuple(params))
        if con_id:
            nuevo = cur.fetchone()
            return Resultado(cur, nuevo[0] if nuevo else None)
        return Resultado(cur)

    def _abrir(self, sql):
        if not self.en_tx and not re.match(r"\s*(SELECT|WITH)\b", sql, re.I):
            self.con.execute("BEGIN")
            self.en_tx = True

    def executemany(self, sql, filas):
        sql = self._traducir(sql)
        self._abrir(sql)
        with self.con.cursor() as cur:
            cur.executemany(sql, filas)

    def bloquear(self, clave):
        """Candado de Postgres hasta confirmar: serializa a todas las instancias (el RLock solo vale dentro de un proceso)."""
        self._abrir("LOCK")
        self.con.execute("SELECT pg_advisory_xact_lock(%s)", (clave,))

    def executescript(self, sql):
        self._abrir(sql)
        self.con.execute(sql)

    def __enter__(self):
        return self

    def __exit__(self, tipo, *_):
        try:
            if self.en_tx:
                self.con.execute("ROLLBACK" if tipo else "COMMIT")
                self.t.version[0] += 1
        finally:
            self.pool.putconn(self.con)
        return False


def conectar():
    t = tenant.actual()
    pool = tenant.pool(t)
    con = pool.getconn()
    if t.schema:        # cada cliente ve solo su schema: el SQL de los módulos no cambia
        try:
            con.execute(f'SET search_path TO "{t.schema}"')
        except Exception:
            pool.putconn(con)
            raise
    return ConexionPG(con, pool, t)


def config(c):
    leer = lambda: {r["clave"]: r["valor"] for r in c.execute("SELECT * FROM config")}
    # dentro de una escritura se lee directo: el consecutivo debe ver lo que esa misma transacción acaba de cambiar
    return dict(leer() if getattr(c, "en_tx", True) else memo("config", leer))


def set_config(c, clave, valor):
    c.execute("INSERT INTO config (clave, valor) VALUES (?,?) ON CONFLICT(clave) DO UPDATE SET valor=excluded.valor",
              (clave, str(valor)))


def siguiente_consecutivo(c, clave):
    n = int(config(c).get(clave) or 1)
    set_config(c, clave, n + 1)
    return n


