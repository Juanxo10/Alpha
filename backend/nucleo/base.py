def crear_tablas(c, esquema):
    # RLS sin políticas: la API pública de Supabase (clave anon) no puede leer nada; la app entra por conexión directa
    c.executescript(esquema + "".join(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;" for t in re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", esquema)))


