# -*- coding: utf-8 -*-
"""Registro de la escritura: inscripción en la ORIP y matrícula inmobiliaria. Etapa de la venta: REGISTRADO."""
import json
import re

from . import seguridad
from .base import ErrorNegocio, ahora, bitacora, crear_tablas, hoy, num

CAMPOS = ("fecha_radicacion", "numero_turno", "fecha_registro", "orip", "matricula_inmobiliaria", "numero_anotacion",
          "numero_predial", "propietario_inscrito", "observaciones")
MATRICULA = re.compile(r"^\d{3}-\d{4,8}$")
FECHA = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ESQUEMA = """
CREATE TABLE IF NOT EXISTS registros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id INTEGER NOT NULL REFERENCES ventas(id), id_lote TEXT NOT NULL,
  estado TEXT NOT NULL DEFAULT 'VIGENTE', fecha_radicacion TEXT, numero_turno TEXT, fecha_registro TEXT NOT NULL,
  orip TEXT NOT NULL, matricula_inmobiliaria TEXT NOT NULL, numero_anotacion TEXT, numero_predial TEXT,
  numero_escritura TEXT, fecha_escritura TEXT, notaria TEXT, propietario_inscrito TEXT,
  valor_derechos_registro DOUBLE PRECISION DEFAULT 0, valor_impuesto_registro DOUBLE PRECISION DEFAULT 0, observaciones TEXT,
  adjuntos TEXT DEFAULT '[]', usuario TEXT, creado TEXT, motivo_anulacion TEXT, fecha_anulacion TEXT);
CREATE INDEX IF NOT EXISTS ix_registros_venta ON registros(venta_id);
"""


LIBRES = {"/api/registro/registrar", "/api/registro/editar"}
CON_APROBACION = {"/api/registro/anular"}


def iniciar(c):
    crear_tablas(c, ESQUEMA)
    seguridad.LIBRE_OPERADOR.update(LIBRES)
    seguridad.REQUIERE_APROBACION.update(CON_APROBACION)
    original = seguridad.resumen_solicitud
    if getattr(original, "_reg", False):
        return

    def resumen(c2, ruta, d):
        if ruta == "/api/registro/anular":
            v = c2.execute("SELECT v.id_lote, cl.nombre FROM ventas v JOIN clientes cl ON cl.id=v.cliente_id WHERE v.id=?",
                           (int(d.get("venta_id") or 0),)).fetchone()
            if v:
                return f"Anular el registro (matrícula) del lote {v['id_lote']} de {v['nombre']}. Motivo: {d.get('motivo', '')}", v["id_lote"]
        return original(c2, ruta, d)
    resumen._reg = True
    seguridad.resumen_solicitud = resumen


def _venta(c, d):
    v = c.execute("SELECT v.*, cl.nombre cliente FROM ventas v JOIN clientes cl ON cl.id=v.cliente_id WHERE v.id=?",
                  (int(d.get("venta_id") or 0),)).fetchone()
    if not v or v["estado"] != "ACTIVA":
        raise ErrorNegocio("La venta no está activa.")
    return v


def _limpiar(c, v, d, actual=None):
    """Valida y devuelve los datos del registro (textos, valores y adjuntos)."""
    x = {k: (d[k] if k in d else (actual[k] if actual else None)) for k in CAMPOS}
    x = {k: (str(val).strip() if val not in (None, "") else None) for k, val in x.items()}
    x["matricula_inmobiliaria"] = (x["matricula_inmobiliaria"] or "").replace(" ", "")
    if not x["fecha_registro"]:
        raise ErrorNegocio("La fecha de registro es obligatoria.")
    if not x["orip"]:
        raise ErrorNegocio("La oficina de registro (ORIP) es obligatoria.")
    if not x["matricula_inmobiliaria"]:
        raise ErrorNegocio("La matrícula inmobiliaria es obligatoria.")
    if not MATRICULA.match(x["matricula_inmobiliaria"]):
        raise ErrorNegocio("La matrícula inmobiliaria debe tener el formato NNN-NNNNNN, por ejemplo 230-123456.")
    for k in ("fecha_registro", "fecha_radicacion"):
        if x[k] and not FECHA.match(x[k]):
            raise ErrorNegocio("Fecha no válida.")
    if x["fecha_registro"] > hoy().isoformat():
        raise ErrorNegocio("La fecha de registro no puede ser futura.")
    if v["fecha_escritura"] and x["fecha_registro"] < v["fecha_escritura"]:
        raise ErrorNegocio("La fecha de registro no puede ser anterior a la fecha de la escritura.")
    if x["fecha_radicacion"] and x["fecha_radicacion"] > x["fecha_registro"]:
        raise ErrorNegocio("La fecha de radicación no puede ser posterior a la fecha de registro.")
    otro = c.execute("SELECT id_lote FROM registros WHERE estado='VIGENTE' AND matricula_inmobiliaria=? AND id_lote<>?",
                     (x["matricula_inmobiliaria"], v["id_lote"])).fetchone()
    if otro:
        raise ErrorNegocio(f"La matrícula {x['matricula_inmobiliaria']} ya está registrada en el lote {otro[0]}.")
    for k in ("valor_derechos_registro", "valor_impuesto_registro"):
        x[k] = round(num(d[k] if k in d else (actual[k] if actual else 0)))
    adj = d["adjuntos"] if "adjuntos" in d else (json.loads(actual["adjuntos"] or "[]") if actual else [])
    ids = [int(a) for a in adj or []]
    for a in ids:
        if not c.execute("SELECT 1 FROM adjuntos WHERE id=? AND id_lote=? AND eliminado=0", (a, v["id_lote"])).fetchone():
            raise ErrorNegocio("Uno de los soportes no pertenece al expediente de este lote.")
    x["adjuntos"] = json.dumps(ids)
    x["propietario_inscrito"] = x["propietario_inscrito"] or v["cliente"]
    return x


def _salida(r):
    if not r:
        return None
    d = dict(r)
    d["adjuntos"] = json.loads(d["adjuntos"] or "[]")
    return d


def vigente(c, venta_id):
    return _salida(c.execute("SELECT * FROM registros WHERE venta_id=? AND estado='VIGENTE' ORDER BY id DESC",
                             (venta_id,)).fetchone())


def historial(c, venta_id):
    return [_salida(r) for r in c.execute("SELECT * FROM registros WHERE venta_id=? ORDER BY id DESC", (venta_id,))]


def get(c, sesion, ruta, q):
    if ruta != "/api/nf/registro":
        return None
    h = historial(c, int(q.get("venta_id") or 0))
    return {"vigente": next((x for x in h if x["estado"] == "VIGENTE"), None), "historial": h}


def acciones(c, usuario, ruta, d):
    if ruta == "/api/registro/registrar":
        v = _venta(c, d)
        if v["etapa"] == "REGISTRADO":
            raise ErrorNegocio("Este lote ya está registrado.")
        if v["etapa"] != "ESCRITURADO":
            raise ErrorNegocio("Solo se puede registrar un lote cuya venta ya esté escriturada.")
        x = _limpiar(c, v, d)
        rid = c.execute(
            "INSERT INTO registros (venta_id, id_lote, fecha_radicacion, numero_turno, fecha_registro, orip, matricula_inmobiliaria,"
            " numero_anotacion, numero_predial, numero_escritura, fecha_escritura, notaria, propietario_inscrito,"
            " valor_derechos_registro, valor_impuesto_registro, observaciones, adjuntos, usuario, creado)"
            " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (v["id"], v["id_lote"], x["fecha_radicacion"], x["numero_turno"], x["fecha_registro"], x["orip"],
             x["matricula_inmobiliaria"], x["numero_anotacion"], x["numero_predial"], v["numero_escritura"],
             v["fecha_escritura"], v["notaria"], x["propietario_inscrito"], x["valor_derechos_registro"],
             x["valor_impuesto_registro"], x["observaciones"], x["adjuntos"], usuario, ahora())).lastrowid
        c.execute("UPDATE ventas SET etapa='REGISTRADO' WHERE id=?", (v["id"],))
        bitacora(c, usuario, "REGISTRO", v["id_lote"], {"registro_id": rid, "venta_id": v["id"], **x})
        return {"ok": True, "id": rid}

    if ruta in ("/api/registro/editar", "/api/registro/anular"):
        v = _venta(c, d)
        r = c.execute("SELECT * FROM registros WHERE venta_id=? AND estado='VIGENTE'", (v["id"],)).fetchone()
        if not r or v["etapa"] != "REGISTRADO":
            raise ErrorNegocio("El lote no tiene un registro vigente.")
        if ruta.endswith("anular"):
            motivo = (d.get("motivo") or "").strip()
            if not motivo:
                raise ErrorNegocio("Indique el motivo de la anulación del registro.")
            c.execute("UPDATE registros SET estado='ANULADO', motivo_anulacion=?, fecha_anulacion=? WHERE id=?",
                      (motivo, hoy().isoformat(), r["id"]))
            c.execute("UPDATE ventas SET etapa='ESCRITURADO' WHERE id=?", (v["id"],))
            bitacora(c, usuario, "REGISTRO_ANULADO", v["id_lote"], {"registro_id": r["id"], "motivo": motivo,
                                                                    "matricula": r["matricula_inmobiliaria"]})
            return {"ok": True}
        x = _limpiar(c, v, d, r)
        c.execute(f"UPDATE registros SET {', '.join(k + '=?' for k in x)} WHERE id=?", (*x.values(), r["id"]))
        bitacora(c, usuario, "REGISTRO_EDITADO", v["id_lote"],
                 {"registro_id": r["id"], "antes": {k: r[k] for k in x}, "despues": x})
        return {"ok": True}
    return None
