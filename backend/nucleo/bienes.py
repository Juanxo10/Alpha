def recibir(c, usuario, d):
    v = c.execute("SELECT * FROM ventas WHERE id=?", (int(d.get("venta_id") or 0),)).fetchone()
    if not v or v["estado"] != "ACTIVA":
        raise ErrorNegocio("El negocio no está activo.")
    tipo, modalidad = d.get("tipo"), d.get("modalidad") or "DACION"
    if tipo not in TIPOS_BIEN or modalidad not in MODALIDADES:
        raise ErrorNegocio("Indique el tipo de bien y la modalidad.")
    desc = (d.get("descripcion") or "").strip()
    if not desc:
        raise ErrorNegocio("Describa el bien.")
    ident = (d.get("identificacion") or "").strip()
    if tipo in ("VEHICULO", "INMUEBLE", "LOTE") and not ident:
        raise ErrorNegocio(f"Indique {TIPOS_BIEN[tipo]['ident'].lower()} del bien.")
    valor = round(num(d.get("valor_recibo"), 0))
    if valor <= 0:
        raise ErrorNegocio("Indique el valor por el que se recibe el bien.")
    fecha = (d.get("fecha_recibo") or hoy().isoformat())[:10]
    if dt.date.fromisoformat(fecha) > hoy():
        raise ErrorNegocio("La fecha de recibo no puede ser futura.")
    n = int(config(c).get("consecutivo_bien") or 1)
    base.set_config(c, "consecutivo_bien", n + 1)
    numero = f"BIEN-{n:04d}"
    tnom = TIPOS_BIEN[tipo]["nombre"].split(" (")[0]
    pago = cartera.registrar_pago(c, usuario, v["id"], {
        "valor": valor, "fecha": fecha, "concepto": d.get("concepto") or "Abono", "medio": "En especie",
        "referencia": f"{numero} · {tnom} {ident}".strip(),
        "observacion": f"{MODALIDADES[modalidad].split(' (')[0]}: {desc}"})
    # no es dinero: no se espera en el extracto bancario
    c.execute("UPDATE pagos SET conciliado=1, conciliacion_ref=? WHERE id=?", (f"Pago en especie {numero}", pago["pago_id"]))
    soportes = [int(x) for x in (d.get("soportes") or []) if str(x).isdigit()]
    bid = c.execute(
        "INSERT INTO bienes_pago (numero, venta_id, id_lote, modalidad, tipo, descripcion, identificacion, marca_modelo, ubicacion, "
        "propietario, propietario_doc, valor_avaluo, fuente_avaluo, valor_recibo, fecha_recibo, pago_id, estado, traspaso, observacion, "
        "soportes, usuario, creado) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
        (numero, v["id"], v["id_lote"], modalidad, tipo, desc, ident, (d.get("marca_modelo") or "").strip(), (d.get("ubicacion") or "").strip(),
         (d.get("propietario") or "").strip(), (d.get("propietario_doc") or "").strip(), num(d.get("valor_avaluo"), 0) or None,
         d.get("fuente_avaluo") or None, valor, fecha, pago["pago_id"], "RECIBIDO",
         "NO_APLICA" if tipo in ("SEMOVIENTES", "OTRO") and d.get("sin_traspaso") else "PENDIENTE",
         (d.get("observacion") or "").strip(), json.dumps(soportes), usuario, ahora())).lastrowid
    bitacora(c, usuario, "BIEN_RECIBIDO", v["id_lote"], {"bien": numero, "tipo": tnom, "descripcion": desc, "identificacion": ident,
                                                        "valor_recibo": valor, "valor_avaluo": num(d.get("valor_avaluo"), 0),
                                                        "recibo": pago["recibo"], "modalidad": modalidad})
    return {"ok": True, "id": bid, "numero": numero, "recibo": pago["recibo"]}


def _bien(c, bid, estados=None):
    b = c.execute("SELECT * FROM bienes_pago WHERE id=?", (int(bid or 0),)).fetchone()
    if not b:
        raise ErrorNegocio("Bien no encontrado.")
    if estados and b["estado"] not in estados:
        raise ErrorNegocio(f"El bien está {ESTADOS[b['estado']].lower()}.")
    return b


def traspaso(c, usuario, d):
    b = _bien(c, d.get("id"), ("RECIBIDO", "EN_VENTA", "VENDIDO"))
    est = d.get("traspaso")
    if est not in TRASPASO:
        raise ErrorNegocio("Estado de traspaso no válido.")
    f = (d.get("fecha_traspaso") or "")[:10] or None
    if est == "HECHO" and not f:
        raise ErrorNegocio("Indique la fecha del traspaso.")
    soportes = json.loads(b["soportes"] or "[]") + [int(x) for x in (d.get("soportes") or []) if str(x).isdigit()]
    c.execute("UPDATE bienes_pago SET traspaso=?, fecha_traspaso=?, soportes=? WHERE id=?", (est, f, json.dumps(soportes), b["id"]))
    bitacora(c, usuario, "BIEN_TRASPASO", b["id_lote"], {"bien": b["numero"], "traspaso": TRASPASO[est], "fecha": f})
    return {"ok": True}


def cambiar_estado(c, usuario, d):
    b = _bien(c, d.get("id"), ("RECIBIDO", "EN_VENTA"))
    est = d.get("estado")
    if est not in ("RECIBIDO", "EN_VENTA"):
        raise ErrorNegocio("Estado no válido.")
    c.execute("UPDATE bienes_pago SET estado=? WHERE id=?", (est, b["id"]))
    bitacora(c, usuario, "BIEN_ESTADO", b["id_lote"], {"bien": b["numero"], "estado": ESTADOS[est]})
    return {"ok": True}


def vender(c, usuario, d):
    b = _bien(c, d.get("id"), ("RECIBIDO", "EN_VENTA"))
    valor = round(num(d.get("valor"), 0))
    if valor <= 0:
        raise ErrorNegocio("Indique el valor de venta del bien.")
    f = (d.get("fecha") or hoy().isoformat())[:10]
    if f < b["fecha_recibo"] or dt.date.fromisoformat(f) > hoy():
        raise ErrorNegocio("La fecha de venta debe estar entre el recibo del bien y hoy.")
    costos = round(num(d.get("costos"), 0))
    c.execute("UPDATE bienes_pago SET estado='VENDIDO', venta_fecha=?, venta_valor=?, venta_costos=?, venta_comprador=?, venta_medio=?, "
              "venta_observacion=? WHERE id=?", (f, valor, costos, (d.get("comprador") or "").strip(), d.get("medio") or "Transferencia",
                                                 (d.get("observacion") or "").strip(), b["id"]))
    resultado = valor - costos - b["valor_recibo"]
    bitacora(c, usuario, "BIEN_VENDIDO", b["id_lote"], {"bien": b["numero"], "valor_venta": valor, "costos": costos,
                                                       "valor_recibo": b["valor_recibo"], "resultado": resultado})
    return {"ok": True, "resultado": resultado}


def anular(c, usuario, d):
    b = _bien(c, d.get("id"), ("RECIBIDO", "EN_VENTA"))
    motivo = (d.get("motivo") or "").strip()
    if not motivo:
        raise ErrorNegocio("Indique el motivo.")
    p = c.execute("SELECT * FROM pagos WHERE id=?", (b["pago_id"],)).fetchone()
    if p and not p["anulado"]:
        c.execute("UPDATE pagos SET anulado=1, motivo_anulacion=?, fecha_anulacion=? WHERE id=?", (f"Anulado el bien {b['numero']}: {motivo}", ahora(), p["id"]))
        bitacora(c, usuario, "ANULAR_PAGO", p["id_lote"], {"recibo": p["recibo"], "valor": p["valor"], "motivo": f"Bien {b['numero']}: {motivo}"})
    c.execute("UPDATE bienes_pago SET estado='ANULADO', motivo_anulacion=?, fecha_anulacion=? WHERE id=?", (motivo, ahora(), b["id"]))
    bitacora(c, usuario, "BIEN_ANULADO", b["id_lote"], {"bien": b["numero"], "motivo": motivo})
    return {"ok": True}


# ---------------------------------------------------------------- consultas
def _fila(r):
    x = dict(r)
    x["tipo_nombre"] = TIPOS_BIEN.get(r["tipo"], {}).get("nombre", r["tipo"]).split(" (")[0]
    x["modalidad_nombre"] = MODALIDADES.get(r["modalidad"], r["modalidad"]).split(" (")[0]
    x["estado_nombre"] = ESTADOS.get(r["estado"], r["estado"])
    x["traspaso_nombre"] = TRASPASO.get(r["traspaso"], r["traspaso"])
    x["soportes"] = json.loads(r["soportes"] or "[]")
    x["dif_avaluo"] = (r["valor_recibo"] - r["valor_avaluo"]) if r["valor_avaluo"] else None
    x["resultado"] = (r["venta_valor"] - (r["venta_costos"] or 0) - r["valor_recibo"]) if r["estado"] == "VENDIDO" else None
    x["dias_inventario"] = ((dt.date.fromisoformat(r["venta_fecha"]) if r["venta_fecha"] else hoy()) - dt.date.fromisoformat(r["fecha_recibo"])).days
    return x


def listar(c, venta_id=None):
    _sincronizar(c)
    sql = ("SELECT b.*, cl.nombre cliente, p.recibo FROM bienes_pago b JOIN ventas v ON v.id=b.venta_id "
           "JOIN clientes cl ON cl.id=v.cliente_id LEFT JOIN pagos p ON p.id=b.pago_id")
    if venta_id:
        filas = [_fila(r) for r in c.execute(sql + " WHERE b.venta_id=? ORDER BY b.id DESC", (int(venta_id),))]
    else:
        filas = [_fila(r) for r in c.execute(sql + " ORDER BY b.id DESC")]
    vivos = [f for f in filas if f["estado"] in ("RECIBIDO", "EN_VENTA")]
    vendidos = [f for f in filas if f["estado"] == "VENDIDO"]
    return {
        "bienes": filas, "tipos": TIPOS_BIEN, "modalidades": MODALIDADES, "fuentes": FUENTES_AVALUO, "estados": ESTADOS, "traspaso": TRASPASO,
        "kpis": {"inventario_n": len(vivos), "inventario_valor": sum(f["valor_recibo"] for f in vivos),
                 "recibido_total": sum(f["valor_recibo"] for f in filas if f["estado"] != "ANULADO"),
                 "traspasos_pendientes": sum(1 for f in filas if f["estado"] != "ANULADO" and f["traspaso"] in ("PENDIENTE", "EN_TRAMITE")),
                 "vendidos_n": len(vendidos), "vendidos_valor": sum(f["venta_valor"] for f in vendidos),
                 "resultado": sum(f["resultado"] for f in vendidos),
                 "sobre_avaluo": sum(1 for f in vivos if f["dif_avaluo"] is not None and f["dif_avaluo"] > 0.5)},
    }


def ajustar_flujo(c, f):
    """La caja del flujo cuenta el dinero real: lo recibido en especie sale de los ingresos del mes y entra cuando el bien
    se vende; los bienes aún sin vender se suman al resultado proyectado como inventario de bienes."""
    try:
        _sincronizar(c)
        esp = {r[0]: r[1] for r in c.execute("SELECT substr(fecha,1,7), SUM(valor) FROM pagos WHERE anulado=0 AND medio='En especie' GROUP BY 1")}
        ven = {r[0]: r[1] for r in c.execute("SELECT substr(venta_fecha,1,7), SUM(venta_valor - COALESCE(venta_costos,0)) FROM bienes_pago "
                                             "WHERE estado='VENDIDO' GROUP BY 1")}
        inv = c.execute("SELECT COALESCE(SUM(valor_recibo),0) FROM bienes_pago WHERE estado IN ('RECIBIDO','EN_VENTA')").fetchone()[0]
    except Exception:  # noqa: BLE001  (sin la tabla todavía)
        return f
    acum = 0.0
    for m in f["meses"]:
        if m["real"]:
            m["ingresos"] += ven.get(m["mes"], 0) - esp.get(m["mes"], 0)
            m["especie"] = esp.get(m["mes"], 0)
            m["venta_bienes"] = ven.get(m["mes"], 0)
        m["neto"] = m["ingresos"] - m["egresos"]
        acum += m["neto"]
        m["acumulado"] = acum
    i = f["indicadores"]
    ajuste = sum(ven.values()) - sum(esp.values())
    i["ingresos"] += ajuste
    i["caja"] += ajuste
    i["resultado_proyectado"] += ajuste + inv
    i["recibido_en_especie"] = sum(esp.values())
    i["bienes_inventario"] = inv
    i["ventas_bienes"] = sum(ven.values())
    return f


