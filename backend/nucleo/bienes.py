"""Bienes recibidos como pago (dación en pago) y permutas.

Un comprador puede pagar todo o parte del lote con un vehículo, un inmueble, otro lote, maquinaria, ganado u otro
bien. El bien se registra con su identificación, su avalúo y el VALOR DE RECIBO acordado; ese valor entra como un
pago del negocio («En especie»), con su recibo de caja, y se aplica al plan de pagos como cualquier otro pago.

Como no es dinero:
  · no se espera en el banco (queda fuera de la conciliación bancaria);
  · no entra a la caja del flujo: el dinero llega cuando el bien se VENDE, y ahí se registra la venta del bien con su
    utilidad o pérdida frente al valor de recibo;
  · mientras no se venda, el bien es un activo del proyecto (inventario de bienes) y así se refleja en el resultado.
El traspaso (tarjeta de propiedad, escritura) se sigue hasta que quede a nombre del vendedor.
"""
import datetime as dt
import json

from . import base, cartera, finanzas, seguridad
from .base import ErrorNegocio, ahora, bitacora, config, hoy, num

TIPOS_BIEN = {
    "VEHICULO": {"nombre": "Vehículo", "ident": "Placa", "icono": "car"},
    "INMUEBLE": {"nombre": "Inmueble (casa, apartamento, local)", "ident": "Matrícula inmobiliaria", "icono": "home"},
    "LOTE": {"nombre": "Lote o finca", "ident": "Matrícula inmobiliaria", "icono": "land-plot"},
    "MAQUINARIA": {"nombre": "Maquinaria o equipo", "ident": "Serie / identificación", "icono": "tractor"},
    "SEMOVIENTES": {"nombre": "Ganado o semovientes", "ident": "Marcas / registro", "icono": "beef"},
    "OTRO": {"nombre": "Otro bien", "ident": "Identificación", "icono": "package"},
}
MODALIDADES = {"DACION": "Dación en pago (parte o todo del precio)", "PERMUTA": "Permuta (cambio del lote por el bien)"}
FUENTES_AVALUO = ["Avalúo comercial", "Revista Motor / Fasecolda", "Avalúo catastral", "Cotización de mercado", "Valor acordado"]
ESTADOS = {"RECIBIDO": "En inventario", "EN_VENTA": "En venta", "VENDIDO": "Vendido", "ANULADO": "Anulado"}
TRASPASO = {"PENDIENTE": "Traspaso pendiente", "EN_TRAMITE": "Traspaso en trámite", "HECHO": "Traspasado", "NO_APLICA": "No requiere"}

ESQUEMA = """
CREATE TABLE IF NOT EXISTS bienes_pago (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT UNIQUE, venta_id INTEGER NOT NULL REFERENCES ventas(id), id_lote TEXT,
  modalidad TEXT NOT NULL, tipo TEXT NOT NULL, descripcion TEXT NOT NULL, identificacion TEXT, marca_modelo TEXT, ubicacion TEXT,
  propietario TEXT, propietario_doc TEXT, valor_avaluo DOUBLE PRECISION, fuente_avaluo TEXT, valor_recibo DOUBLE PRECISION NOT NULL, fecha_recibo TEXT NOT NULL,
  pago_id INTEGER REFERENCES pagos(id), estado TEXT NOT NULL DEFAULT 'RECIBIDO', traspaso TEXT NOT NULL DEFAULT 'PENDIENTE',
  fecha_traspaso TEXT, observacion TEXT, soportes TEXT,
  venta_fecha TEXT, venta_valor DOUBLE PRECISION, venta_costos DOUBLE PRECISION, venta_comprador TEXT, venta_medio TEXT, venta_observacion TEXT,
  motivo_anulacion TEXT, fecha_anulacion TEXT, usuario TEXT, creado TEXT);
CREATE INDEX IF NOT EXISTS ix_bienes_venta ON bienes_pago(venta_id);
"""
LIBRES = {"/api/bien/traspaso", "/api/bien/estado"}
CON_APROBACION = {"/api/bien/recibir", "/api/bien/vender", "/api/bien/anular"}


def _pesos(v):
    return "$" + format(int(round(num(v, 0))), ",d").replace(",", ".")


def iniciar(c):
    base.crear_tablas(c, ESQUEMA)
    seguridad.LIBRE_OPERADOR.update(LIBRES)
    seguridad.REQUIERE_APROBACION.update(CON_APROBACION)
    if not getattr(seguridad.resumen_solicitud, "_nf_bienes", False):
        original = seguridad.resumen_solicitud

        def resumen(c2, ruta, d):
            if ruta == "/api/bien/recibir":
                v = c2.execute("SELECT id_lote FROM ventas WHERE id=?", (int(d.get("venta_id") or 0),)).fetchone()
                tipo = TIPOS_BIEN.get(d.get("tipo"), {}).get("nombre", "bien")
                av = f" (avalúo {_pesos(d.get('valor_avaluo'))})" if num(d.get("valor_avaluo"), 0) else " (sin avalúo)"
                return (f"Recibir como pago del lote {v[0] if v else ''} un {tipo.lower()}: {d.get('descripcion', '')} "
                        f"{d.get('identificacion', '')}, por {_pesos(d.get('valor_recibo'))}{av}", v[0] if v else None)
            if ruta in ("/api/bien/vender", "/api/bien/anular"):
                b = c2.execute("SELECT numero, descripcion, id_lote, valor_recibo FROM bienes_pago WHERE id=?", (int(d.get("id") or 0),)).fetchone()
                if b:
                    if ruta.endswith("vender"):
                        return (f"Registrar la venta del bien {b['numero']} ({b['descripcion']}) por {_pesos(d.get('valor'))}; "
                                f"se recibió por {_pesos(b['valor_recibo'])}", b["id_lote"])
                    return f"Anular el bien {b['numero']} ({b['descripcion']}) y su recibo. Motivo: {d.get('motivo', '')}", b["id_lote"]
            return original(c2, ruta, d)
        resumen._nf_bienes = True
        seguridad.resumen_solicitud = resumen
    # el flujo de caja separa lo recibido en especie de la caja real
    if not getattr(finanzas.flujo, "_nf_bienes", False):
        flujo_base = finanzas.flujo

        def flujo(c2, *a, **k):
            return ajustar_flujo(c2, flujo_base(c2, *a, **k))
        flujo._nf_bienes = True
        finanzas.flujo = flujo


def _sincronizar(c):
    """Si alguien anuló directamente el recibo del bien, el bien queda anulado también."""
    for b in c.execute("SELECT b.id, b.numero, b.id_lote FROM bienes_pago b JOIN pagos p ON p.id=b.pago_id "
                       "WHERE p.anulado=1 AND b.estado IN ('RECIBIDO','EN_VENTA')").fetchall():
        c.execute("UPDATE bienes_pago SET estado='ANULADO', motivo_anulacion='Se anuló su recibo de caja', fecha_anulacion=? WHERE id=?",
                  (ahora(), b["id"]))


