def get(c, sesion, ruta, q):
    if ruta == "/api/bienes":
        return listar(c, q.get("venta_id"))
    if ruta == "/api/bien":
        _sincronizar(c)
        r = c.execute("SELECT b.*, cl.nombre cliente, p.recibo FROM bienes_pago b JOIN ventas v ON v.id=b.venta_id "
                      "JOIN clientes cl ON cl.id=v.cliente_id LEFT JOIN pagos p ON p.id=b.pago_id WHERE b.id=?", (int(q.get("id") or 0),)).fetchone()
        if not r:
            raise ErrorNegocio("Bien no encontrado.")
        x = _fila(r)
        x["adjuntos"] = [dict(a) for a in c.execute("SELECT id, tipo, nombre, tamano, creado FROM adjuntos WHERE id IN (%s) AND COALESCE(eliminado,0)=0"
                                                    % ",".join("?" * len(x["soportes"])), x["soportes"])] if x["soportes"] else []
        return x
    return None


def acciones(c, usuario, ruta, d):
    if ruta == "/api/bien/recibir":
        return recibir(c, usuario, d)
    if ruta == "/api/bien/traspaso":
        return traspaso(c, usuario, d)
    if ruta == "/api/bien/estado":
        return cambiar_estado(c, usuario, d)
    if ruta == "/api/bien/vender":
        return vender(c, usuario, d)
    if ruta == "/api/bien/anular":
        return anular(c, usuario, d)
    return None
